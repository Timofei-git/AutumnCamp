# Дан словарь покупок вида {"хлеб": 45, "молоко": 89, ...}.
# Посчитай и выведи общую сумму покупок, перебрав словарь циклом.

buys = {"Хлеб": 45, "Молоко": 89, "Апельсин": 30}

sum = 0
for key, value in buys.items():
    print(f"{key}: {value}")
    sum += value

print(f'Total sum of buys: {sum}')